from experiments.search.run_leftovers_1m import read_rows

OUT_DIR = os.path.join(mk.RESULTS_DIR, "ac19_orig_10m")
JSONL = "ac19_orig_10m_greedy_b10000000_mrl64.jsonl"
OUT = os.path.join(OUT_DIR, "WORKED_EXAMPLE.md")
# The cheapest path in the set: 23 moves, 509 nodes. Short enough to print in
# full, which is the only reason to prefer it.
ROW = "ac19x_144949"


def profile(rec, phi):
    a = [len(s[0]) + len(s[1]) for s in rec["path"]]
    b = []
    for s in rec["path"]:
        p = canon_pair(apply_hom(s[0], phi), apply_hom(s[1], phi))
        b.append(len(p[0]) + len(p[1]))
    return a, b


def move_desc(target, sign):
    return f"`r{target} <- r{target}·(c⁻¹ r{3 - target}{'' if sign > 0 else '⁻¹'} c)`"


def render(recs):
    by = {r["name"]: r for r in recs}
    rec = by[ROW]
    orbit = {r["name"]: r["orbit"] for r in mk.build()["greedy"]}[ROW]
    orig = (rec["r1"], rec["r2"])
    _, rep, phi = aut_canon(orig)
    states, moves = rec["path"], rec["path_moves"]

    L = []
    w = L.append
    w("# One row, move by move: why the aut-min form travels further")
    w("")
    w("Generated by `experiments/search/make_ac19_worked_example.py`; do not edit.")
    w("The theorem this illustrates is in `RESULTS.md`, section \"The theorem\".")
    w("")
    w(f"`{rec['name']}` is the cheapest solve in the set, which is the only reason")
    w("it was picked: 23 moves is short enough to print in full.")
    w("")
    w("| | pair | total length |")
    w("|---|---|---:|")
    w(f"| original, `{rec['name']}` | `({orig[0]}, {orig[1]})` | {sum(map(len, orig))} |")
    w(f"| aut-min representative, `{orbit}` | `({rep[0]}, {rep[1]})` "
      f"| {sum(map(len, rep))} |")
    w("")
    w(f"The automorphism `aut_canon` returns is **`x -> {phi['x']}`, `y -> {phi['y']}`**.")
    w(f"Greedy solved the original in **{rec['nodes_explored']:,} nodes**. Its aut-min")
    w("representative is unsolved at 10,000,000.")
    w("")
    w("## The two columns are the same moves")
    w("")
    w("Each row is one AC move. `c` is the move's conjugator word in the original's")
    w("basis; the aut-min side runs the identical move with `phi(c)` instead. Both")
    w("`len` columns are the total relator length after the move.")
    w("")
    w("| # | move | c | original pair | len | aut-min pair | len |")
    w("|---:|---|---|---|---:|---|---:|")
    s0 = tuple(states[0])
    a0 = canon_pair(apply_hom(s0[0], phi), apply_hom(s0[1], phi))
    w(f"| 0 | *(start)* | | `({s0[0]}, {s0[1]})` | {sum(map(len, s0))} | "
      f"`({a0[0]}, {a0[1]})` | {sum(map(len, a0))} |")
    for i, m in enumerate(moves):
        cur, nxt = tuple(states[i]), tuple(states[i + 1])
        target, sign, c = to_conjugator(cur, tuple(int(v) for v in m.split("_")))
        an = canon_pair(apply_hom(nxt[0], phi), apply_hom(nxt[1], phi))
        w(f"| {i + 1} | {move_desc(target, sign)} | `{c or '-'}` | "
          f"`({nxt[0]}, {nxt[1]})` | {sum(map(len, nxt))} | "
          f"`({an[0]}, {an[1]})` | {sum(map(len, an))} |")

    basis = canon_pair(apply_hom(states[-1][0], phi), apply_hom(states[-1][1], phi))
    tail = reduce_basis(basis)
    w("")
    w(f"**The original is finished at move {len(moves)}**, at `({states[-1][0]}, "
      f"{states[-1][1]})`. The aut-min side sits at `({basis[0]}, {basis[1]})`: a")
    w("basis of F2, but not two single letters. That is what the tail is for.")
    w("")
    w("| # | move | c | aut-min pair | len |")
    w("|---:|---|---|---|---:|")
    cur = basis
    for j, tm in enumerate(tail):
        t2, s2, c2 = to_conjugator(cur, tm)
        nxt = tuple(moves_to_states(cur[0], cur[1], [tm])[-1])
        w(f"| {len(moves) + j + 1} | {move_desc(t2, s2)} | `{c2 or '-'}` | "
          f"`({nxt[0]}, {nxt[1]})` | {sum(map(len, nxt))} |")
        cur = nxt
    w("")
    w(f"**{len(moves)} moves for the original, {len(moves) + len(tail)} for the "
      "representative.** The whole difference is the tail.")
    w("")

    w("## Why the aut-min side climbs")
    w("")
    w("Look at moves 17 to 23. Both sides are doing the same thing over and over,")
    w("peeling one factor off the second relator:")
    w("")
    w("| | move 17 | move 20 | move 23 |")
    w("|---|---|---|---|")
    for label, fn in (("original", lambda s: s),
                      ("aut-min", lambda s: canon_pair(apply_hom(s[0], phi),
                                                       apply_hom(s[1], phi)))):
        cells = []
        for k in (17, 20, 23):
            p = fn(tuple(states[k]))
            cells.append(f"`({p[0]}, {p[1]})`")
        w(f"| {label} | " + " | ".join(cells) + " |")
    w("")
    w(f"The original strips one letter at a time. The aut-min side strips one")
    w(f"**`{phi['y']}` block** at a time, because that is what `phi` turns a single")
    w(f"`y` into. Same computation, letters three times as long.")
    w("")
    w("That is the whole mechanism. `phi` is a change of coordinates chosen to make")
    w("**one point** short, the starting pair. It is applied to every other point on")
    w("the route as well, and there it inflates rather than shrinks. The trade is")
    w("measurable across all 40 originals:")
    w("")

    starts_o, starts_a, peaks_o, peaks_a, gaps = [], [], [], [], []
    higher = shorter = 0
    for r in recs:
        _, _, p = aut_canon((r["r1"], r["r2"]))
        a, b = profile(r, p)
        starts_o.append(a[0]); starts_a.append(b[0])
        peaks_o.append(max(a)); peaks_a.append(max(b))
        gaps.append(max(b) - max(a))
        higher += max(b) > max(a)
        shorter += b[0] < a[0]
    w("| over the 40 originals | starting length | peak length along the path |")
    w("|---|---:|---:|")
    w(f"| original, median | {st.median(starts_o):.0f} | {st.median(peaks_o):.0f} |")
    w(f"| aut-min, median | **{st.median(starts_a):.0f}** | **{st.median(peaks_a):.0f}** |")
    w("")
    w(f"Aut-minimising buys a shorter start on {shorter} of {len(recs)} rows and pays")
    w(f"for it with a higher peak on **{higher} of {len(recs)}** -- every one. The peak")
    w(f"ratio runs from {min(pb / pa for pa, pb in zip(peaks_o, peaks_a)):.2f} to "
      f"{max(pb / pa for pa, pb in zip(peaks_o, peaks_a)):.2f}, median "
      f"{st.median([pb / pa for pa, pb in zip(peaks_o, peaks_a)]):.2f}.")
    w("")
    w("## Why a higher peak is an exponentially worse search")
    w("")
    w("The arms are best-first on length: `greedy`'s priority IS the total length,")
    w("and `s20_mk2`'s leads with it. Such a search pops states in roughly increasing")
    w("length, so to find a path whose peak is `P` it must be willing to work through")
    w("the states below `P`. The number of cyclically reduced words of length `n` in")
    w("F2 grows like `3^n`, so the territory is exponential in the peak.")
    w("")
    w(f"The median row's peak rises by {st.median(gaps):.0f} letters when you")
    w(f"aut-minimise. That is a factor of about `3^{st.median(gaps):.0f}`, roughly")
    w(f"{3 ** int(st.median(gaps)):.0g}, in the size of the region a length-guided")
    w("search has to cover. Against that, the gap between 509 nodes and a failure at")
    w("10,000,000 is unsurprising.")
    w("")
    w("This is the precise sense in which a **shorter presentation is a harder**")
    w("problem here. Short means sitting at the bottom of the length landscape, and")
    w("the exit is over a ridge.")
    w("")
    w("## What this does not show")
    w("")
    w("It does not show the aut-min pair has no short route of its own. It shows that")
    w("**this** route, the one inherited from the original, is a bad one for it. Some")
    w("other path might stay low the whole way. Nobody has found one: that is exactly")
    w("what 10,000,000 nodes failed to do, and the transported certificate is an upper")
    w("bound, not a distance.")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    recs = read_rows(os.path.join(OUT_DIR, JSONL))
    if len(recs) != 40:
        raise RuntimeError(f"expected 40 records, found {len(recs)}")
    text = render(recs)
    if args.check:
        drift = not os.path.exists(OUT) or open(OUT).read() != text
        print("  DRIFT" if drift else "  no drift", os.path.relpath(OUT))
        return 1 if drift else 0
    with open(OUT, "w") as fh:
        fh.write(text)
    print(f"  wrote {os.path.relpath(OUT)} ({os.path.getsize(OUT):,} B)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
