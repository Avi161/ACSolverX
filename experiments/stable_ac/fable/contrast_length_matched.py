"""Length-matched re-analysis of the stable-class contrast -- an audit of our own headline.

The raw numbers from `stable_matched_contrast` read as a huge separation: the AK(2)+z
positive control is 14,999/27,350 SPHERICAL (54.8%), the AK(3)+z open target is
0/171,842.  That comparison is NOT sound as stated, and this module exists to say so
with numbers rather than to defend it.

The harvest pops by ASCENDING total length, and the two classes have very different
length profiles: AK(2)+z is trivializable, so its class shrinks -- the harvest reaches
total length 3 (the standard presentation itself) and spends most of its budget at
lengths 3-11, where thickenable states are common.  AK(3)+z's harvest never produces a
member below length 14.  So the raw contrast conflates two different statements:

    (a) thickenable members are common in AK(2)+z's class, and
    (b) AK(2)+z's class contains SHORT members and short members are usually thickenable.

Only a per-length comparison separates them.  This module recomputes the spherical rate
restricted to the length band the two harvests actually SHARE, and reports the
correlation structure of the control's hits (how many distinct parents they descend
from), because class members are generated by a move tree and are emphatically not
independent draws -- a p-value computed as if they were would be fiction.

Claims addressed: none.  This is measurement and self-audit; it produces no statement
about AC-triviality, stable AC-triviality, or the trivial group.
"""

from __future__ import annotations

import argparse
import gzip
import json
import os
import sys
from collections import Counter, defaultdict

_HERE = os.path.dirname(os.path.abspath(__file__))
if _HERE not in sys.path:
    sys.path.insert(0, _HERE)

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(_HERE)))
RESULTS = os.path.join(REPO_ROOT, "results", "stable_ac", "fable")
DEFAULT_OUT = os.path.join(RESULTS, "contrast_length_matched.json")

SOURCES = (
    ("AK2+z", os.path.join(RESULTS, "stable_contrast_ak2z_members.jsonl.gz")),
    ("AK3+z", os.path.join(RESULTS, "stable_contrast_ak3z_members.jsonl.gz")),
)


def scan(path: str) -> dict:
    """Per-length member and spherical counts, plus the hits' parent multiset."""
    members: Counter = Counter()
    spherical: Counter = Counter()
    undecided: Counter = Counter()
    hit_parents: Counter = Counter()
    hit_rows = []
    total = 0
    with gzip.open(path, "rt", encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            words = row.get("canonical") or row.get("pair") or []
            length = row.get("total_length")
            if length is None:
                length = sum(len(w) for w in words)
            total += 1
            members[length] += 1
            verdict = row.get("verdict")
            if verdict == "SPHERICAL":
                spherical[length] += 1
                parent = row.get("parent_key")
                hit_parents[json.dumps(parent) if parent is not None else "ROOT"] += 1
                if len(hit_rows) < 40:
                    hit_rows.append({"canonical": words, "total_length": length,
                                     "first_seen_pop": row.get("first_seen_pop"),
                                     "parent_key": parent})
            elif verdict == "UNDECIDED_BUDGET":
                undecided[length] += 1
    return {"path": os.path.relpath(path, REPO_ROOT), "members_total": total,
            "members_by_length": dict(sorted(members.items())),
            "spherical_by_length": dict(sorted(spherical.items())),
            "undecided_by_length": dict(sorted(undecided.items())),
            "spherical_total": sum(spherical.values()),
            "distinct_parents_of_hits": len(hit_parents),
            "largest_parent_family": max(hit_parents.values()) if hit_parents else 0,
            "sample_hits": hit_rows}


def run(out_path: str = DEFAULT_OUT) -> dict:
    scans = {}
    for name, path in SOURCES:
        if not os.path.exists(path):
            scans[name] = {"status": "MISSING", "path": path}
            continue
        scans[name] = scan(path)
        print(f"[match] {name}: {scans[name]['members_total']} members, "
              f"{scans[name]['spherical_total']} spherical", flush=True)

    control, target = scans.get("AK2+z"), scans.get("AK3+z")
    report = {"record": "contrast_length_matched", "scans": scans,
              "claims_addressed": "none -- measurement and self-audit only"}

    if control and target and "members_by_length" in control:
        c_len = {int(k): v for k, v in control["members_by_length"].items()}
        t_len = {int(k): v for k, v in target["members_by_length"].items()}
        c_sph = {int(k): v for k, v in control["spherical_by_length"].items()}
        t_sph = {int(k): v for k, v in target["spherical_by_length"].items()}
        band = sorted(set(c_len) & set(t_len))
        rows = []
        c_band = t_band = c_hits = t_hits = 0
        for length in band:
            rows.append({"total_length": length,
                         "control_members": c_len.get(length, 0),
                         "control_spherical": c_sph.get(length, 0),
                         "target_members": t_len.get(length, 0),
                         "target_spherical": t_sph.get(length, 0)})
            c_band += c_len.get(length, 0)
            t_band += t_len.get(length, 0)
            c_hits += c_sph.get(length, 0)
            t_hits += t_sph.get(length, 0)
        rate = (c_hits / c_band) if c_band else 0.0
        report["shared_band"] = {
            "lengths": [band[0], band[-1]] if band else [],
            "per_length": rows,
            "control_members": c_band, "control_spherical": c_hits,
            "control_rate_in_band": rate,
            "target_members": t_band, "target_spherical": t_hits,
            "target_expected_at_control_rate": round(rate * t_band, 1),
        }
        report["raw_comparison"] = {
            "control_rate_all_lengths": (control["spherical_total"]
                                         / control["members_total"]),
            "target_rate_all_lengths": (target["spherical_total"]
                                        / target["members_total"]),
            "why_unsound": ("the two harvests occupy different length bands; the "
                            "control reaches total length 3 (the standard "
                            "presentation) while the target never goes below 14, and "
                            "short states are disproportionately thickenable"),
        }
        report["independence_caveat"] = {
            "control_distinct_parents_of_hits": control["distinct_parents_of_hits"],
            "control_largest_parent_family": control["largest_parent_family"],
            "note": ("class members are generated by a move tree and are NOT "
                     "independent draws; no p-value is quoted, and the expected "
                     "count above is a descriptive scale, not a test statistic"),
        }
        print(f"[match] shared band {band[0]}-{band[-1]}: control "
              f"{c_hits}/{c_band} = {rate:.4%}; target {t_hits}/{t_band}; "
              f"expected-at-control-rate {report['shared_band']['target_expected_at_control_rate']}",
              flush=True)

    with open(out_path, "w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=1)
    print(f"[match] wrote {out_path}", flush=True)
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    run(args.out)


if __name__ == "__main__":
    main()
