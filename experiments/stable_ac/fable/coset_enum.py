"""A small HLT Todd-Coxeter coset enumerator over the trivial subgroup.

Used on this line only as the ``pi_1(K_P) = 1`` verifier required by Corollary 3: an
enumeration that completes with index 1 certifies that the presentation presents the
trivial group.  Nothing else in the stack depends on it, and a capped (incomplete)
enumeration is reported as such -- never as a completed index.

Alphabet convention (generic over the generating set): the generators are distinct
single lowercase characters and a word is a string in which the uppercase form of a
generator denotes its inverse.  Column ``2g`` of the coset table is generator ``g`` and
column ``2g + 1`` is ``g^-1``.

The algorithm is HLT with coincidence processing (Holt, *Handbook of Computational
Group Theory*, section 5.2): relators are scanned at each live coset in the given
order, gaps are filled by new definitions, and coincidences are queued and processed
with a union-find on coset numbers.  The scan order is fixed, so runs are
deterministic.
"""

from __future__ import annotations

COMPLETE = "COMPLETE"
CAP_EXCEEDED = "CAP_EXCEEDED"

DEFAULT_COSET_CAP = 20_000


class CosetEnumerationError(ValueError):
    """Malformed input to the enumerator."""


class _CapExceeded(Exception):
    pass


def parse_word(word: str, generators) -> tuple:
    """Turn ``word`` into a tuple of column indices for ``generators``."""
    index = {}
    for g, name in enumerate(generators):
        if len(name) != 1 or not name.islower():
            raise CosetEnumerationError(
                f"generator {name!r} must be a single lowercase character"
            )
        index[name] = 2 * g
        index[name.upper()] = 2 * g + 1
    out = []
    for c in word:
        if c not in index:
            raise CosetEnumerationError(f"letter {c!r} is not over {tuple(generators)}")
        out.append(index[c])
    return tuple(out)


def _inv(column: int) -> int:
    return column ^ 1


def enumerate_cosets(generators, relators, subgroup_generators=(),
                     cap: int = DEFAULT_COSET_CAP) -> dict:
    """Enumerate cosets of the subgroup generated by ``subgroup_generators``.

    Returns a dict with ``status`` (``COMPLETE`` / ``CAP_EXCEEDED``), ``index`` (the
    number of live cosets, or ``None`` when capped), ``cosets_defined`` and
    ``max_table_size``.
    """
    generators = tuple(generators)
    if len(set(generators)) != len(generators):
        raise CosetEnumerationError("duplicate generator")
    n_cols = 2 * len(generators)
    if n_cols == 0:
        raise CosetEnumerationError("no generators")
    rel = [parse_word(w, generators) for w in relators]
    sub = [parse_word(w, generators) for w in subgroup_generators]

    # coset 0 is unused so that 0 can mean "undefined"
    table = [[0] * n_cols, [0] * n_cols]
    p = [0, 1]
    defined = 1

    def rep(k: int) -> int:
        root = k
        while p[root] != root:
            root = p[root]
        while p[k] != root:
            p[k], k = root, p[k]
        return root

    def define(alpha: int, x: int) -> None:
        nonlocal defined
        if defined >= cap:
            raise _CapExceeded()
        beta = len(table)
        table.append([0] * n_cols)
        p.append(beta)
        defined += 1
        table[alpha][x] = beta
        table[beta][_inv(x)] = alpha

    def merge(k: int, l: int, queue: list) -> None:
        k, l = rep(k), rep(l)
        if k == l:
            return
        if k > l:
            k, l = l, k
        p[l] = k
        queue.append(l)

    def coincidence(a: int, b: int) -> None:
        queue: list = []
        merge(a, b, queue)
        i = 0
        while i < len(queue):
            e = queue[i]
            i += 1
            for x in range(n_cols):
                f = table[e][x]
                if f == 0:
                    continue
                table[f][_inv(x)] = 0
                e1 = rep(e)
                f1 = rep(f)
                if table[e1][x] != 0:
                    merge(f1, table[e1][x], queue)
                elif table[f1][_inv(x)] != 0:
                    merge(e1, table[f1][_inv(x)], queue)
                else:
                    table[e1][x] = f1
                    table[f1][_inv(x)] = e1

    def scan_and_fill(alpha: int, word: tuple) -> None:
        if not word:
            return
        while True:
            f, i = alpha, 0
            j = len(word) - 1
            while i <= j and table[f][word[i]] != 0:
                f = table[f][word[i]]
                i += 1
            if i > j:
                if f != alpha:
                    coincidence(f, alpha)
                return
            b = alpha
            while j >= i and table[b][_inv(word[j])] != 0:
                b = table[b][_inv(word[j])]
                j -= 1
            if j < i:
                coincidence(f, b)
                return
            if j == i:
                table[f][word[i]] = b
                table[b][_inv(word[i])] = f
                return
            define(f, word[i])

    status = COMPLETE
    try:
        for word in sub:
            scan_and_fill(1, word)
        alpha = 1
        while alpha < len(table):
            if rep(alpha) == alpha:
                for word in rel:
                    scan_and_fill(alpha, word)
                    if rep(alpha) != alpha:
                        break
                if rep(alpha) == alpha:
                    for x in range(n_cols):
                        if table[alpha][x] == 0:
                            define(alpha, x)
            alpha += 1
    except _CapExceeded:
        status = CAP_EXCEEDED

    live = sum(1 for k in range(1, len(table)) if rep(k) == k)
    return {
        "status": status,
        "index": live if status == COMPLETE else None,
        "live_cosets": live,
        "cosets_defined": defined,
        "max_table_size": len(table) - 1,
        "cap": cap,
        "generators": generators,
        "relators": tuple(relators),
        "subgroup_generators": tuple(subgroup_generators),
    }


def coset_index(generators, relators, subgroup_generators=(),
                cap: int = DEFAULT_COSET_CAP) -> int:
    """The index, or ``ValueError`` if the enumeration hit the cap."""
    result = enumerate_cosets(generators, relators, subgroup_generators, cap)
    if result["status"] != COMPLETE:
        raise ValueError(
            f"coset enumeration hit the cap of {cap} cosets; index undetermined"
        )
    return result["index"]


def is_trivial_group(words, generators=("x", "y"), cap: int = DEFAULT_COSET_CAP) -> dict:
    """Certify ``pi_1`` of the presentation complex of ``words`` is trivial.

    Returns the enumeration report with an extra ``trivial`` key: ``True`` only when a
    complete enumeration returned index 1, ``False`` for a complete enumeration with a
    larger index, and ``None`` when the cap was hit (undetermined, never guessed).
    """
    result = enumerate_cosets(generators, words, (), cap)
    if result["status"] != COMPLETE:
        result["trivial"] = None
    else:
        result["trivial"] = result["index"] == 1
    return result
