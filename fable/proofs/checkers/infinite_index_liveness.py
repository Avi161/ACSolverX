def defect_image(cp, defect):
    out = {}
    for vtx, cf in defect.items():
        om = cp.omega(cp.trace(wstr(vtx)))
        out[om] = out.get(om, 0) + cf
    return {k: a for k, a in out.items() if a}


def winv(w):
    return "".join(INV[x] for x in reversed(w))


def word_family(cp, states, L, align=0):
    """The reduced words v the rows are taken over.

    The ball of radius L, plus -- when `align` > 0 -- the ALIGNED family
    `winv(escape word of a state) + u`, |u| <= align.  A state sitting at
    depth D in a cone is only ever brought back to the core by a v whose
    first D letters spell its escape word backwards, so a plain ball of
    radius L < D carries no row in which that entry is shallow.  Every
    aligned word is an ordinary element of Q, so the rows it contributes are
    ordinary elements of the lattice: aligning changes which certificates
    are FOUND, never which are VALID.
    """
    out = {v for v in reduced_words(L)}
    if align:
        for terms in states.values():
            for (u_core, esc), _a in terms:
                if not esc:
                    continue
                pref = winv("".join(esc))
                for u in reduced_words(align):
                    v = pref
                    for x in u:
                        v = v[:-1] if (v and x == INV[v[-1]]) else v + x
                    out.add(v)
    return sorted(out, key=lambda w: (len(w), w))


def build_rows(cp, states, L, align=0):
    """{(i, v): row} over the word family, deduped by row."""
    out, seen = {}, set()
    for v in word_family(cp, states, L, align):
        for i in (0, 1):
            row = row_sigma(cp, states[i], v)
            if not row:
                continue
            key = tuple(sorted(row.items()))
            if key in seen:
                continue
            seen.add(key)
            out[(i, v)] = row
    return out


def coverage(cp, Z, rows):
    """per-depth count of Omega-classes with [w] - [w_base] in the lattice."""
    om0 = cp.omega(cp.base)
    cls = {c for row in rows.values() for c in row}
    per = {}
    for c in cls:
        d = depth(c)
        ok = True if c == om0 else Z.member({c: 1, om0: -1})[0]
        a, b = per.get(d, (0, 0))
        per[d] = (a + int(ok), b + 1)
    full = -1
    for d in sorted(per):
        if per[d][0] == per[d][1]:
            full = d
        else:
            break
    return full, {str(d): list(per[d]) for d in sorted(per)}


