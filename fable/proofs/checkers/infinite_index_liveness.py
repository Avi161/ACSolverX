def mode_lift(args, rows):
    """Explicit integral x with D + sum_i L_i x_i = 0, verified in M."""
    sel = [r for r in rows if not Completed(
        GS.Folded(GS.gamma_gens(r["chain"], r["g_gen"]))).finite]
    if args.chains:
        a, b = args.chains.split(":")
        sel = sel[int(a or 0):int(b or len(sel))]
    out, ok, mutated = [], True, False
    for r in sel:
        ch, g, cp, ops, defect, h, sl = chain_setup(r, k=args.k)
        for k0 in range(-args.k, args.k + 1):
            for k2 in range(-args.k, args.k + 1):
                ops_w, dfc, _h = GS.window_data(ch, g, sl, (k0, 0, k2, 0))
                sol = seeded_lift(cp, ch, _h, ops_w, dfc, args)
                rec = {"chain": r["chain"], "g": g, "window": [k0, 0, k2, 0],
                       "defect_terms": len(dfc), "rho": args.rho,
                       "variables": sol["variables"],
                       "route": sol.get("route"),
                       "solvable_over_Z": sol["ok"],
                       "x_terms": sol["x_terms"],
                       "residual_after_lift": sol["residual"],
                       "VERIFIED_layer1_solution": sol["ok"]
                       and sol["residual"] == 0}
                if sol["ok"] and not mutated:
                    bad = list(ops_w)
                    d4 = dict(bad[4])
                    d4.pop(sorted(d4)[0])
                    bad[4] = d4
                    still = verify(dfc, tuple(bad), sol["x"])
                    print(json.dumps({
                        "control": "mutation_breaks_verified_solution",
                        "residual_after_corruption": len(still),
                        "passed": bool(still)}))
                    ok = ok and bool(still)
                    mutated = True
                ok = ok and (not sol["ok"] or sol["residual"] == 0)
                out.append(rec)
                print(json.dumps(rec))
    summ = {"windows": len(out),
            "verified_layer1_solutions": sum(
                1 for o in out if o["VERIFIED_layer1_solution"]),
            "unsolved_at_rho": sum(1 for o in out if not o["solvable_over_Z"]),
            "mutation_control_run": mutated,
            "controls_passed": ok and bool(out)}
    print(json.dumps({"summary": summ}))
    _dump(args, "lift", summ, out)
    return 0 if summ["controls_passed"] else 2


def solve_module(ops, defect, rho):
    """D + sum_i L_i x_i = 0 over Z, variables from a rho-HOP expansion.

    W2b's `one_hop_system` is the rho = 1 case: variables (i, v) whose column
    L_i e_v meets supp(D).  Here the expansion is iterated rho times, so the
    truncation W2b/W2e/W2f inherit is relaxed rather than replaced by a
    radius ball (which wastes columns far from the defect).  A solution found
    at any rho is an exact solution of the untruncated equation.
    """
    return solve_module_from(ops, defect, rho, [], range(5))


def solve_module_from(ops, defect, rho, seed, which):
    """As solve_module, with extra seed variables and an operator subset."""
    frontier = set(defect)
    seen_v, variables = set(seed), list(seed)
    for (i, v) in seed:
        frontier.update(apply_operator(ops[i], {v: 1}))
    for _ in range(rho):
        if len(variables) > 40000:
            break
        new_v = []
        for i in which:
            op = ops[i]
            for gw in op:
                gi = quotient_inverse(gw)
                for u in frontier:
                    v = c_vertex(quotient_multiply(gi, u))
                    if (i, v) not in seen_v:
                        seen_v.add((i, v))
                        new_v.append((i, v))
        variables.extend(new_v)
        frontier = set()
        for (i, v) in new_v:
            frontier.update(apply_operator(ops[i], {v: 1}))
    Z = ZEchelon(order=lambda w: (-len(w), w))
    for (i, v) in variables:
        img = apply_operator(ops[i], {v: 1})
        if img:
            Z.add(img, (i, v))
    member, combo = Z.member({k: -a for k, a in defect.items()})
    if not member:
        return {"ok": False, "x": None, "x_terms": None,
                "variables": len(variables), "residual": None}
    x = [dict() for _ in range(5)]
    for (i, v), cf in combo.items():
        x[i][v] = x[i].get(v, 0) + cf
    return {"ok": True, "x": x, "x_terms": [len(xi) for xi in x],
            "variables": len(variables),
            "residual": len(verify(defect, ops, x))}


def seeded_lift(cp, ch, h, ops, defect, args):
    """Explicit x, seeded by the Omega witness.

    The Omega lattice decides D in sum_i L_i M and hands back an integer
    combination of L0/L1 columns; the residual then lies in
    ker(pi) = I_Gamma M = L2 M + L3 M + L4 M by Lemma 2, so only the
    telescoping operators are needed to finish it.  Seeding the module
    system with the witness's own columns is what makes the finish local.
    """
    states = sigma_states(cp, ch, h)
    rws = build_rows(cp, states, int(args.radii.split(",")[-1]), args.align)
    Z = ZEchelon(order=DEEP_FIRST)
    for tag, row in rws.items():
        Z.add(row, tag)
    member, combo = Z.member(defect_image(cp, defect))
    seed = []
    y = [dict() for _ in range(5)]
    if member:
        for (i, v), cf in combo.items():
            vv = c_vertex(LV.to_tuple(v))
            y[i][vv] = y[i].get(vv, 0) + cf
            seed.append((i, vv))
        resid = dict(defect)
        for i, yi in enumerate(y):
            if yi:
                resid = add_vectors(resid, apply_operator(
                    ops[i], {k: -a for k, a in yi.items()}))
        resid = {k: a for k, a in resid.items() if a}
        sol = solve_module_from(ops, resid, args.resid_rho or args.rho,
                                [], (2, 3, 4))
        print(json.dumps({"omega_witness_terms": len(combo),
                          "residual_terms_in_I_Gamma_M": len(resid),
                          "telescoping_solve": sol["ok"],
                          "telescoping_variables": sol["variables"]}))
        if sol["ok"]:
            x = [{k: -a for k, a in yi.items()} for yi in y]
            for i in (2, 3, 4):
                for k, a in sol["x"][i].items():
                    x[i][k] = x[i].get(k, 0) + a
            x = [{k: a for k, a in xi.items() if a} for xi in x]
            return {"ok": True, "x": x, "x_terms": [len(xi) for xi in x],
                    "variables": sol["variables"], "route": "omega_seeded",
                    "residual": len(verify(defect, ops, x))}
    out = solve_module(ops, defect, args.rho)
    out["route"] = "hop_expansion"
    return out


def verify(defect, ops, x):
    """D + sum L_i x_i with the unmodified certificate primitives."""
    acc = dict(defect)
    for i, xi in enumerate(x):
        if xi:
            acc = add_vectors(acc, apply_operator(ops[i], xi))
    return {k: v for k, v in acc.items() if v}


def mode_probe(args, rows):
    """POSITIVE control: the detector must be able to fire.

    On the real systems the lattice contains pi(D), so nothing can ever be
    certified dead -- a detector that never fires is not evidence.  So it is
    run on a SYNTHETIC system with L0, L1 doubled (L2, L3, L4 untouched),
    whose Omega-lattice is 2A by construction.  A PRIMITIVE Omega-difference
    defect must then be certified NOT in the image, its double must be, and
    the independent one-hop solver must agree that the primitive one is
    unsolvable mod 2.
    """
    sel = [r for r in rows if not Completed(
        GS.Folded(GS.gamma_gens(r["chain"], r["g_gen"]))).finite]
    if args.chains:
        a, b = args.chains.split(":")
        sel = sel[int(a or 0):int(b or len(sel))]
    out, ok, fired = [], True, 0
    for r in sel:
        ch, g, cp, ops, defect, h, _sl = chain_setup(r)
        states = sigma_states(cp, ch, h)
        L = int(args.radii.split(",")[0])
        rws = build_rows(cp, states, L, args.align)
        Z = ZEchelon(order=DEEP_FIRST)
        for tag, row in rws.items():
            Z.add(row, tag)
        piD = defect_image(cp, defect)
        real_ok = Z.member(piD)[0]
        # synthetic: doubled L0, L1 -> every row doubled -> lattice 2A
        Zs = ZEchelon(order=DEEP_FIRST)
        for tag, row in rws.items():
            Zs.add({k: 2 * a for k, a in row.items()}, tag)
        # a primitive Omega-difference: two module vertices in distinct classes
        pair = None
        for s in PS.ball(6):
            v1 = c_vertex(LV.to_tuple(s))
            o1 = cp.omega(cp.trace(wstr(v1)))
            for s2 in PS.ball(6):
                v2 = c_vertex(LV.to_tuple(s2))
                o2 = cp.omega(cp.trace(wstr(v2)))
                if o1 != o2 and Z.member({o1: 1, o2: -1})[0]:
                    pair = (v1, v2, o1, o2)
                    break
            if pair:
                break
        if pair is None:
            rec = {"chain": r["chain"], "g": g,
                   "status": "NO_PRIMITIVE_PAIR_FOUND", "passed": False}
            ok = False
            out.append(rec)
            print(json.dumps(rec))
            continue
        v1, v2, o1, o2 = pair
        odd = {o1: 1, o2: -1}
        even = {o1: 2, o2: -2}
        syn_ops = (LV.add_group_ring(ops[0], ops[0]),
                   LV.add_group_ring(ops[1], ops[1]),
                   ops[2], ops[3], ops[4])
        mod_defect = {v1: 1, v2: -1}
        rows_o, rhs_o, _ = LV.one_hop_system(mod_defect, syn_ops)
        rec = {"chain": r["chain"], "g": g,
               "real_piD_in_lattice": real_ok,
               "synthetic_primitive_in_lattice": Zs.member(odd)[0],
               "synthetic_double_in_lattice": Zs.member(even)[0],
               "one_hop_solvable_mod2": bool(
                   LV.solve_mod_p(rows_o, rhs_o, 2)),
               "primitive_in_real_lattice": Z.member(odd)[0]}
        rec["detector_fires_on_primitive"] = (
            not rec["synthetic_primitive_in_lattice"])
        rec["detector_silent_on_double"] = rec["synthetic_double_in_lattice"]
        rec["one_hop_agrees_primitive_dead_mod2"] = (
            rec["one_hop_solvable_mod2"] is False)
        rec["passed"] = (rec["detector_fires_on_primitive"]
                         and rec["detector_silent_on_double"]
                         and rec["one_hop_agrees_primitive_dead_mod2"]
                         and rec["primitive_in_real_lattice"])
        fired += int(rec["detector_fires_on_primitive"])
        ok = ok and rec["passed"]
        out.append(rec)
        print(json.dumps(rec))
    summ = {"chains": len(out), "detector_fired": fired,
            "all_controls_passed": ok and bool(out),
            "note": "the real lattice contains pi(D) on every chain, so no "
                    "real chain can be certified dead; the detector is shown "
                    "able to fire on a synthetic doubled system, and the "
                    "independent one-hop solver agrees"}
    print(json.dumps({"summary": summ}))
    _dump(args, "probe", summ, out)
    return 0 if summ["all_controls_passed"] else 2


def mode_period(args, rows):
    """The window axes on the completed graph."""
    sel = [r for r in rows if not Completed(
        GS.Folded(GS.gamma_gens(r["chain"], r["g_gen"]))).finite]
    if args.chains:
        a, b = args.chains.split(":")
        sel = sel[int(a or 0):int(b or len(sel))]
    L = int(args.radii.split(",")[0])
    out, ok = [], True
    for r in sel:
        ch = tuple(r["chain"])
        g = r["g_gen"]
        cp = Completed(GS.Folded(GS.gamma_gens(ch, g)))
        sl = PS.chain_slots_g(ch, g, args.k, args.k)
        z2, z3 = sl["h2"]["zeta"], sl["h3"]["zeta"]
        # does zeta act trivially on the completed graph?
        ball = [v for v in reduced_words(args.radius)]
        triv2 = all(cp.walk(cp.trace(v), z2) == cp.trace(v) for v in ball)
        triv3 = all(cp.walk(cp.trace(v), z3) == cp.trace(v) for v in ball)
        seen = []
        for k0 in range(-args.k, args.k + 1):
            for k1 in range(-args.k, args.k + 1):
                for k2 in range(-args.k, args.k + 1):
                    for k3 in range(-args.k, args.k + 1):
                        ops, dfc, h = GS.window_data(ch, g, sl,
                                                     (k0, k1, k2, k3))
                        states = sigma_states(cp, ch, h)
                        rws = build_rows(cp, states, L, args.align)
                        Z = ZEchelon(order=DEEP_FIRST)
                        for tag, row in rws.items():
                            Z.add(row, tag)
                        piD = defect_image(cp, dfc)
                        full, _ = coverage(cp, Z, rws)
                        seen.append({"w": [k0, k1, k2, k3],
                                     "in": Z.member(piD)[0],
                                     "aug": sum(piD.values()),
                                     "margin": L - full})
        rec = {"chain": r["chain"], "g": g, "K": args.k, "L": L,
               "zeta2_acts_trivially_on_ball": triv2,
               "zeta3_acts_trivially_on_ball": triv3,
               "windows": len(seen),
               "windows_with_piD_in_lattice": sum(1 for s in seen if s["in"]),
               "margins": sorted({s["margin"] for s in seen}),
               "augmentations": sorted({s["aug"] for s in seen})}
        rec["all_windows_solvable"] = (
            rec["windows_with_piD_in_lattice"] == rec["windows"])
        ok = ok and rec["augmentations"] == [0]
        out.append(rec)
        print(json.dumps(rec))
    summ = {"chains": len(out),
            "all_windows_solvable": sum(1 for o in out
                                        if o["all_windows_solvable"]),
            "zeta_trivial_on_ball": sum(
                1 for o in out if o["zeta2_acts_trivially_on_ball"]
                and o["zeta3_acts_trivially_on_ball"]),
            "controls_passed": ok and bool(out)}
    print(json.dumps({"summary": summ}))
    _dump(args, "period", summ, out)
    return 0 if summ["controls_passed"] else 2


def _dump(args, name, summ, rows):
    if args.json:
        Path(args.json).write_text(json.dumps(
            {"schema": f"acsolverx.w2h.{name}.v1",
             "summary": summ, "rows": rows}, indent=1))


