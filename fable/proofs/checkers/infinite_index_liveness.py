# ------------------------------------------------------------ words


def wstr(tup):
    """LV letter tuple -> reduced word over {'c','t','T'}."""
    return "".join("c" if abs(l) == C else ("t" if l == T else "T")
                   for l in tup)


def reduced_words(maxlen):
    """Every reduced word over {c,t,T} (no cc, tT, Tt) of length <= maxlen."""
    yield ""
    frontier = [""]
    for _ in range(maxlen):
        nxt = []
        for w in frontier:
            for x in "ctT":
                if w and x == INV[w[-1]]:
                    continue
                nxt.append(w + x)
                yield w + x
        frontier = nxt


