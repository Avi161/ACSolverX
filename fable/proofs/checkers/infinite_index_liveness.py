def sigma_terms(chain, h):
    """{i: [(group element, sign)]} realising pi(L_i e_v) -- see module docstring."""
    R, S, _U = chain
    qR, qS = GS.q(R), GS.q(S)
    qA = quotient_reduce(LV.SOURCE_A)
    qB = quotient_reduce(LV.SOURCE_B)
    h2, h3 = GS.q(h[2]), GS.q(h[3])
    beta = quotient_multiply(quotient_inverse(qS), qB)
    return {
        0: [(qR, +1),
            (quotient_multiply(h2, qR), +1),
            (quotient_multiply(h3, qR), +1),
            (qA, -1),
            (quotient_multiply(h2, qA), -1),
            (quotient_multiply(h3, qA), -1)],
        1: [(quotient_multiply(h2, beta), +1),
            (quotient_multiply(h3, beta), +1),
            (h2, -1),
            (h3, -1)],
    }


def sigma_states(cp, chain, h):
    return {i: [(cp.trace(wstr(gw)), a) for gw, a in terms]
            for i, terms in sigma_terms(chain, h).items()}


def row_sigma(cp, states_i, v):
    row = {}
    for s, a in states_i:
        om = cp.omega(cp.walk(s, v))
        row[om] = row.get(om, 0) + a
    return {k: a for k, a in row.items() if a}


def row_direct(cp, op, v):
    """Omega-row of the column L_i e_v, straight off the operator."""
    row = {}
    for gw, a in op.items():
        om = cp.omega(cp.trace(wstr(gw) + v))
        row[om] = row.get(om, 0) + a
    return {k: a for k, a in row.items() if a}


# ------------------------------------------- exact integer row lattice


def _lin(a, u, b, v):
    out = {}
    for k, x in u.items():
        y = a * x
        if y:
            out[k] = y
    for k, x in v.items():
        y = out.get(k, 0) + b * x
        if y:
            out[k] = y
        elif k in out:
            del out[k]
    return out


def _egcd(a, b):
    if b == 0:
        return (abs(a), 1 if a >= 0 else -1, 0)
    old_r, r = a, b
    old_s, s = 1, 0
    old_t, t = 0, 1
    while r:
        qq = old_r // r
        old_r, r = r, old_r - qq * r
        old_s, s = s, old_s - qq * s
        old_t, t = t, old_t - qq * t
    if old_r < 0:
        old_r, old_s, old_t = -old_r, -old_s, -old_t
    return old_r, old_s, old_t


class ZEchelon:
    """Hermite-style echelon of a lattice of sparse integer vectors.

    Exact over Z (not a mod-p or rational shadow): membership answers
    "is this vector an INTEGER combination of the rows added so far".
    Combination coefficients are tracked so every positive answer ships a
    witness that is re-multiplied out and compared term by term.
    """

    def __init__(self, order=None):
        self.piv = {}
        self.order = order or (lambda c: c)

    def _key(self, v):
        return min(v, key=self.order)

    def add(self, vec, tag):
        v = {k: a for k, a in vec.items() if a}
        c = {tag: 1}
        while v:
            col = self._key(v)
            if col not in self.piv:
                if v[col] < 0:
                    v = _lin(-1, v, 0, {})
                    c = _lin(-1, c, 0, {})
                self.piv[col] = (v, c)
                return
            pr, pc = self.piv[col]
            a, b = v[col], pr[col]
            if a % b == 0:
                f = a // b
                v = _lin(1, v, -f, pr)
                c = _lin(1, c, -f, pc)
            else:
                gg, x, y = _egcd(b, a)
                nr = _lin(x, pr, y, v)
                nc = _lin(x, pc, y, c)
                f1, f2 = b // gg, a // gg
                v = _lin(f1, v, -f2, pr)
                c = _lin(f1, c, -f2, pc)
                self.piv[col] = (nr, nc)

    def member(self, vec):
        v = {k: a for k, a in vec.items() if a}
        c = {}
        while v:
            col = self._key(v)
            if col not in self.piv:
                return False, None
            pr, pc = self.piv[col]
            if v[col] % pr[col]:
                return False, None
            f = v[col] // pr[col]
            v = _lin(1, v, -f, pr)
            c = _lin(1, c, -f, pc)
        return True, {k: -a for k, a in c.items()}


