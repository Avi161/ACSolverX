def mode_identity(args, rows):
    """EFFECTIVE control for the sigma-tuple identity and for Lemma 2'."""
    sel = rows if not args.stratum_only else [r for r in rows if r["stratum"]]
    if args.chains:
        a, b = args.chains.split(":")
