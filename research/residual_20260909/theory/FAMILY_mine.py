"""Mine the AC19 census for the *families* of the 41 rows the 1,000-unit ball
cascade (`K3p_c12aut`) leaves unsolved.

A **family** is a set of census rows that share a relator up to the symmetry
group generated by cyclic rotation, relator inversion and the eight signed
permutations of ``{x, y}`` (``words.SIGNED_PERMS``).  ``orbit_key`` is the
canonical representative of that orbit, computed as
``min_phi canon_rel(phi(R))``; two relators are in the same orbit iff their
keys are equal.  Rotation and inversion are already quotiented by
``words.canon_rel``, so the key is a complete invariant of the orbit.

Everything here is read-only with respect to ``results/`` and ``data/``.

CLI
---
    PYTHONPATH=. python3 research/residual_20260909/theory/FAMILY_mine.py --build
        build (and cache) the census relator-orbit index

    PYTHONPATH=. python3 research/residual_20260909/theory/FAMILY_mine.py --report
        write FAMILY_mine.json: per-family tables used by FAMILY_DATA.md
"""
