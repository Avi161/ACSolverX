def load_census():
    with open(CENSUS, newline='') as stream:
        return list(csv.DictReader(stream))


def load_unsolved():
    with open(UNSOLVED, newline='') as stream:
        return list(csv.DictReader(stream))


def build_index(rows=None, verbose=True):
    """``orbit_key -> [(name, role), ...]`` over the whole census."""
    rows = load_census() if rows is None else rows
    index = defaultdict(list)
    for row in rows:
        k1, k2 = orbit_key(row['r1']), orbit_key(row['r2'])
        index[k1].append((row['name'], 1))
        if k2 != k1:
            index[k2].append((row['name'], 2))
    index = dict(index)
    if verbose:
        print(f'index: {len(index)} orbit keys over {len(rows)} rows', file=sys.stderr)
    return index


def load_index(rebuild=False):
    if CACHE.exists() and not rebuild:
        with open(CACHE, 'rb') as stream:
            return pickle.load(stream)
    index = build_index()
    with open(CACHE, 'wb') as stream:
        pickle.dump(index, stream)
    return index


def _shards(directory):
    out = []
    for path in sorted(glob.glob(str(Path(directory) / 'rows_*.jsonl'))):
        match = re.match(r'rows_(\d+)_(\d+)\.jsonl', os.path.basename(path))
        out.append((int(match.group(1)), int(match.group(2)), path))
    return out


def load_records(names, directory=BALL):
    """Certificate records for ``names`` from a census result directory."""
    want = set(names)
    out = {}
    for _lo, _hi, path in _shards(directory):
        with open(path) as stream:
            for line in stream:
                if not line.strip():
                    continue
                record = json.loads(line)
                if record.get('name') in want:
                    out[record['name']] = record
        if len(out) == len(want):
            break
    return out


# --------------------------------------------------------------------------
# path analysis
# --------------------------------------------------------------------------
def parse_move(text):
    target, jsign, k1, k2 = (int(v) for v in text.split('_'))
    return target, jsign, k1, k2


def step_summary(states, steps):
    """One compact token per certificate step: ``S1``/``S2`` for a
    substitution onto relator 1/2, ``A`` for an ambient Nielsen map."""
    out = []
    for step in steps:
        if step.get('kind') == 'automorphism':
            out.append('A')
        else:
            target = parse_move(step['move'])[0]
            out.append(f'S{target}')
    return out


def donor_trace(record, family_relator_canon):
    """For each substitution step, which relator was the *donor* (source), and
    was the root family relator still intact at that point?

    Returns a dict with the first-donor role, the number of steps until the
    family relator is first modified, and the compact step string.
    """
    states = [tuple(s) for s in record['states']]
    steps = record['steps']
    tokens = step_summary(states, steps)
    fam = family_relator_canon
    first_touch = None       # index of the first step that removes fam from the pair
    first_donor = None       # 'family' or 'companion'
    for i, (state, step) in enumerate(zip(states, steps)):
        present = fam in (canon_rel(state[0]), canon_rel(state[1]))
        if step.get('kind') == 'automorphism':
            if present and first_touch is None:
                first_touch = i
                first_donor = 'automorphism'
            continue
        target = parse_move(step['move'])[0]
        # the donor is the *other* relator
        donor_word = canon_rel(state[1] if target == 1 else state[0])
        target_word = canon_rel(state[0] if target == 1 else state[1])
        if first_donor is None and present:
            if donor_word == fam:
                first_donor = 'family'
            elif target_word == fam:
                first_donor = 'companion'   # family relator is being overwritten
        if present and target_word == fam and first_touch is None:
            first_touch = i
    return dict(tokens=tokens, first_donor=first_donor, first_touch=first_touch,
                n_steps=len(steps))


def replay_check(pair, states, steps):
    """Independently re-run a mixed certificate with words.replay_move /
    words.apply_pair; returns True iff every stored state is reproduced."""
    cur = canon_pair(*pair)
    if list(cur) != [canon_rel(states[0][0]), canon_rel(states[0][1])] and \
       tuple(cur) != tuple(states[0]):
        cur = tuple(states[0])
    for i, step in enumerate(steps):
        if step.get('kind') == 'automorphism':
            cur = apply_pair(cur, step['images'])
        else:
            cur = replay_move(cur, parse_move(step['move']))
        if tuple(cur) != tuple(states[i + 1]):
            return False
    return True


# --------------------------------------------------------------------------
# family assembly
# --------------------------------------------------------------------------
def family(key, index=None, census=None, records=True):
    index = load_index() if index is None else index
    census = load_census() if census is None else census
    by_name = {row['name']: row for row in census}
    members = []
    for name, _role in index.get(key, ()):
        row = by_name[name]
        frame = normalize_row(row['r1'], row['r2'], key)
        members.append(dict(name=name, index=int(row['name'].split('_')[1]),
                            r1=row['r1'], r2=row['r2'], **frame))
    members.sort(key=lambda m: m['index'])
    if records:
        recs = load_records([m['name'] for m in members])
        for m in members:
            r = recs.get(m['name'])
            m['record'] = r
    return members


