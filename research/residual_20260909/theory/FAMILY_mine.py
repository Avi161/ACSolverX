    parser.add_argument('--families', action='store_true', help='print the family table')
    args = parser.parse_args(argv)
    index = load_index(rebuild=args.build)
    if args.families:
        uns = load_unsolved()
        fams = defaultdict(list)
        for row in uns:
            fams[orbit_key(row['r1'])].append(row['name'])
        print(f"{'family':22s} {'|R|':>3} {'ex':>3} {'ey':>3} {'unsolved':>8} {'census':>7}")
        for key, names in sorted(fams.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            ex, ey = exp_sums(key)
            print(f'{key:22s} {len(key):3d} {ex:3d} {ey:3d} {len(names):8d} '
                  f'{len(index.get(key, [])):7d}  ' + ','.join(names))
    return 0


