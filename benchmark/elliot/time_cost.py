"""Time-weighted cost of ACSolverES Dual / Triple GS: how much a CoV step costs next to a substitution pop.

`nodes` counts one per pop from any queue, so a CoV pop counts the same as a substitution pop, and the CoV work
of seeding the start state is not charged at all. Here every CoV child is generated by a Python callback that the
C++ engine calls (`run_compact_dual_gs(..., expander)`, `run_compact_triple_gs(..., auto, complete)`); we wrap those
callbacks with a timer, without changing ACSolverES. Per row:

    callback_s    CPU seconds inside the CoV callbacks (seeding and CoV pops), by kind
    engine_s      cpu_s - callback_s: the C++ search (substitution children, queues, dedup)
    t_pop         engine_s / nodes, pooled over a benchmark and method: one substitution pop
    cost_units    nodes + callback_s / t_pop: the run in substitution-pop units, CoV work included

A substitution pop does the work of one LENGTH expansion (same S-move children, length priority), so cost_units
are LENGTH-expansion units algorithmically; seconds are not comparable with acx's Python timings (C++ engine).

Usage:
  python benchmark/elliot/time_cost.py --out results/elliot_cost --workers 2
  python benchmark/elliot/time_cost.py --summarize results/elliot_cost [--md results/elliot_cost/COST_TABLE.md]
"""
from __future__ import annotations

import argparse
import json
import os
import statistics as st
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

os.environ.setdefault("NUMBA_NUM_THREADS", "1")
sys.path.insert(0, str(Path(__file__).resolve().parent))
import run_elliot as R  # noqa: E402

BUDGET = 100_000  # every row of the three benchmarks is solved within 20,819 nodes
LABEL = {
    "single_auto_cov_dual": "Dual, single CoV",
    "auto_dual": "Dual, auto CoV",
    "auto_nonauto_cov_triple": "Triple",
}

_STATS: dict = {}


def _timed(kind, fn):
    def wrapper(state, source_queue):
        t0 = time.process_time()
        out = fn(state, source_queue)
        dt = time.process_time() - t0
        phase = "seed" if "seed" in str(source_queue) else "pop"
        key = f"{kind}_{phase}"
        _STATS.setdefault(key, [0, 0.0])
        _STATS[key][0] += 1
        _STATS[key][1] += dt
        return out
    return wrapper


class _DualProxy:
    def __init__(self, real, kind):
        self._real, self._kind = real, kind

    def __getattr__(self, name):
        return getattr(self._real, name)

    def run_compact_dual_gs(self, r1, r2, expander, *args, **kw):
        return self._real.run_compact_dual_gs(r1, r2, _timed(self._kind, expander), *args, **kw)


class _TripleProxy:
    def __init__(self, real):
        self._real = real

    def __getattr__(self, name):
        return getattr(self._real, name)

    def run_compact_triple_gs(self, r1, r2, auto, complete, *args, **kw):
        return self._real.run_compact_triple_gs(
            r1, r2, _timed("auto", auto), _timed("complete", complete), *args, **kw)


def _install():
    from ac_final_paper.solvers import compact_dual_gs, dual_auto_cov_gs, triple_gs
    if not isinstance(compact_dual_gs._native, _DualProxy):
        compact_dual_gs._native = _DualProxy(compact_dual_gs._native, "single")
        dual_auto_cov_gs._native = _DualProxy(dual_auto_cov_gs._native, "auto")
        triple_gs._compact_triple_native = _TripleProxy(triple_gs._compact_triple_native)


def _warm(_=None):
    from ac_final_paper import algorithm_adapters as aa
    _install()
    aa.warm_up(max_len=R.MAX_LEN)
    # compile the CoV generators on real states before anything is timed
    for algo in R.ALGOS:
        for pres in (("YYXyx", "Yx"), ("xxxYYYY", "xyxYXY")):
            run_row(algo, "warm", *pres, budget=2_000)
    return True


def run_row(algo, pid, r1, r2, budget=BUDGET):
    from ac_final_paper import algorithm_adapters as aa
    _install()
    _STATS.clear()
    params = dict(R.PAPER_PARAMS[algo])
    params.update(total_node_budget=budget, max_len=R.MAX_LEN, max_live_frontier_states=None)
    c0, w0 = time.process_time(), time.perf_counter()
    res = aa.run_algorithm(algo, (r1, r2), params)
    cpu, wall = time.process_time() - c0, time.perf_counter() - w0
    cb = {k: {"calls": v[0], "s": v[1]} for k, v in _STATS.items()}
    callback_s = sum(v["s"] for v in cb.values())
    pops = {
        "sub": res.get("sub_pop_count", 0),
        "single": res.get("cov_pop_count", 0) if algo == "single_auto_cov_dual" else 0,
        "auto": (res.get("auto_cov_queue_pop_count") or res.get("automorphism_queue_pop_count")
                 or (res.get("cov_pop_count", 0) if algo == "auto_dual" else 0)),
        "complete": res.get("complete_cov_queue_pop_count", 0),
    }
    return {
        "algo": algo, "id": pid, "r1": r1, "r2": r2, "budget": budget,
        "solved": bool(res.get("solved")), "nodes": int(res["total_nodes_used"]),
        "pops": pops, "cpu_s": cpu, "wall_s": wall, "callback_s": callback_s,
        "engine_s": max(cpu - callback_s, 0.0), "callbacks": cb,
        "frontier_prune_count": res.get("frontier_prune_count"),
    }


def run(out: Path, workers: int, benches, algos):
    out.mkdir(parents=True, exist_ok=True)
    jobs = []
    for bench in benches:
        rows = R.load_bench(bench)
        for algo in algos:
            f = out / f"{bench}__{algo}.jsonl"
            done = {json.loads(l)["id"] for l in f.read_text().splitlines()} if f.exists() else set()
            jobs += [(bench, algo, pid, r1, r2) for pid, r1, r2 in rows if pid not in done]
    print(f"{len(jobs)} rows", flush=True)
    handles = {}
    with ProcessPoolExecutor(workers, initializer=_warm) as ex:
        futs = {ex.submit(run_row, algo, pid, r1, r2): (bench, algo) for bench, algo, pid, r1, r2 in jobs}
        for n, fut in enumerate(as_completed(futs), 1):
            bench, algo = futs[fut]
            rec = fut.result()
            rec["bench"] = bench
            if (bench, algo) not in handles:
                handles[bench, algo] = (out / f"{bench}__{algo}.jsonl").open("a")
            handles[bench, algo].write(json.dumps(rec) + "\n")
            handles[bench, algo].flush()
            if n % 200 == 0:
                print(n, flush=True)
    for h in handles.values():
        h.close()


def summarize(folder: Path, md: str | None):
    lines = [
        "| benchmark | method | nodes | CoV pops | CPU s | CoV callback share of CPU | t_pop (us) "
        "| seed cost (pops) | CoV pop cost (pops) | cost units | cost / nodes |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for bench in ("ms640", "bench60", "ladder100"):
        for algo in R.ALGOS:
            f = folder / f"{bench}__{algo}.jsonl"
            if not f.exists():
                continue
            recs = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
            nodes = sum(r["nodes"] for r in recs)
            cpu = sum(r["cpu_s"] for r in recs)
            cbs = sum(r["callback_s"] for r in recs)
            t_pop = sum(r["engine_s"] for r in recs) / nodes
            cov_pops = sum(r["pops"]["single"] + r["pops"]["auto"] + r["pops"]["complete"] for r in recs)
            seed_calls = sum(v["calls"] for r in recs for k, v in r["callbacks"].items() if k.endswith("_seed"))
            seed_s = sum(v["s"] for r in recs for k, v in r["callbacks"].items() if k.endswith("_seed"))
            pop_calls = sum(v["calls"] for r in recs for k, v in r["callbacks"].items() if k.endswith("_pop"))
            pop_s = sum(v["s"] for r in recs for k, v in r["callbacks"].items() if k.endswith("_pop"))
            cost = nodes + cbs / t_pop
            seed_cost = (seed_s / seed_calls / t_pop) if seed_calls else 0
            pop_cost = (pop_s / pop_calls / t_pop + 1) if pop_calls else 0
            lines.append(
                f"| {bench} | {LABEL[algo]} | {nodes:,} | {cov_pops:,} | {cpu:,.1f} | {cbs / cpu:.0%} "
                f"| {t_pop * 1e6:,.1f} | {seed_cost:,.0f} | {pop_cost:,.0f} | {cost:,.0f} | {cost / nodes:.2f} |"
            )
    lines += [
        "",
        "Solved within a budget B, counted in nodes and in cost units (CoV work included):",
        "",
        "| benchmark | method | nodes <= 1e3 / 1e4 / 1e5 | cost <= 1e3 / 1e4 / 1e5 | cost median | cost max |",
        "|---|---|---|---|---:|---:|",
    ]
    for bench in ("ms640", "bench60", "ladder100"):
        for algo in R.ALGOS:
            f = folder / f"{bench}__{algo}.jsonl"
            if not f.exists():
                continue
            recs = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
            t_pop = sum(r["engine_s"] for r in recs) / sum(r["nodes"] for r in recs)
            cost = sorted(r["nodes"] + r["callback_s"] / t_pop for r in recs if r["solved"])
            nodes = [r["nodes"] for r in recs if r["solved"]]
            by = lambda xs: " / ".join(str(sum(x <= b for x in xs)) for b in (1e3, 1e4, 1e5))
            lines.append(f"| {bench} | {LABEL[algo]} | {by(nodes)} | {by(cost)} "
                         f"| {st.median(cost):,.0f} | {cost[-1]:,.0f} |")
    text = "\n".join(lines)
    print(text)
    if md:
        Path(md).write_text(text + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/elliot_cost")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--benches", default="ms640,bench60,ladder100")
    ap.add_argument("--algos", default=",".join(R.ALGOS))
    ap.add_argument("--summarize")
    ap.add_argument("--md")
    a = ap.parse_args()
    if a.summarize:
        summarize(Path(a.summarize), a.md)
    else:
        run(Path(a.out), a.workers, a.benches.split(","), a.algos.split(","))


if __name__ == "__main__":
    main()
